"""Read the NASA GIBS WMTS GetCapabilities (EPSG:3857) and write js/gibs-layers.js.

Layer identifiers, formats, tile matrix sets (maximum zoom), date ranges and legend URLs are copied from
the capabilities document, so the page never uses an invented identifier.
Run:  python analysis/gibs_layers.py            (downloads the capabilities, about 6 MB)
      python analysis/gibs_layers.py caps.xml   (uses a saved copy)
Code written with AI assistance (Anthropic Claude) and reviewed by the team.
"""
import datetime as dt
import json
import sys
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

CAPS = "https://gibs.earthdata.nasa.gov/wmts/epsg3857/best/1.0.0/WMTSCapabilities.xml"
NS = {"w": "http://www.opengis.net/wmts/1.0", "ows": "http://www.opengis.net/ows/1.1"}
XLINK = "{http://www.w3.org/1999/xlink}href"

# What we show, in the order of the layer menu. "role" is only for the page.
WANTED = [
    ("VIIRS_NOAA20_CorrectedReflectance_TrueColor", "base", "True color (VIIRS, NOAA-20)", None, None),
    ("MODIS_Terra_L3_Land_Surface_Temp_Monthly_Day", "overlay", "Land surface temperature, day (MODIS Terra, monthly)",
     "lst", "Monthly mean daytime land surface temperature from MODIS on Terra. Land only. The scale is in kelvin: 300 K is about 27 °C (subtract 273.15)."),
    ("IMERG_Precipitation_Rate", "overlay", "Precipitation rate (GPM IMERG, daily)",
     "imerg", "Daily precipitation rate from the GPM IMERG multi-satellite product."),
    ("GHRSST_L4_MUR25_Sea_Surface_Temperature_Anomalies", "overlay", "Sea surface temperature anomaly (GHRSST MUR25, daily)",
     "ssta", "Daily sea surface temperature anomaly from the GHRSST Level 4 MUR 0.25 degree analysis. Ocean only."),
]


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else None
    data = Path(src).read_bytes() if src else urllib.request.urlopen(CAPS, timeout=120).read()
    root = ET.fromstring(data)
    found = {}
    for layer in root.find("w:Contents", NS).findall("w:Layer", NS):
        ident = layer.find("ows:Identifier", NS).text
        found[ident] = layer
    out = []
    for ident, role, title, key, about in WANTED:
        layer = found.get(ident)
        if layer is None:
            raise SystemExit(f"Layer {ident} is not in the GIBS capabilities: choose another one.")
        fmt = layer.find("w:Format", NS).text
        tms = layer.find("w:TileMatrixSetLink/w:TileMatrixSet", NS).text
        dims = {}
        for d in layer.findall("w:Dimension", NS):
            dims[d.find("ows:Identifier", NS).text] = {
                "default": d.find("w:Default", NS).text,
                "values": [v.text for v in d.findall("w:Value", NS)],
            }
        time = dims.get("Time")
        legend = None
        for s in layer.findall("w:Style", NS):
            for lu in s.findall("w:LegendURL", NS):
                href = lu.get(XLINK)
                if href and href.endswith("_H.svg"):
                    legend = href
        out.append({
            "id": ident, "key": key or ident, "role": role, "title": title, "about": about,
            "gibsTitle": layer.find("ows:Title", NS).text,
            "format": fmt, "ext": "png" if fmt == "image/png" else "jpeg",
            "tileMatrixSet": tms, "maxzoom": int(tms.rsplit("Level", 1)[1]),
            "period": (time["values"][0].rsplit("/", 1)[1] if time else None),
            "defaultTime": time["default"] if time else None,
            "intervals": [v.split("/")[:2] for v in time["values"]] if time else [],
            "legend": legend,
        })
    stamp = dt.date.today().isoformat()
    js = (
        "/* NASA GIBS layers used by the map, generated by analysis/gibs_layers.py from\n"
        f"   {CAPS}\n   on {stamp}. Do not edit by hand: run the script again to refresh dates.\n"
        "   Code written with AI assistance (Anthropic Claude). */\n"
        f"export const GIBS_CAPABILITIES = {json.dumps(CAPS)};\n"
        f"export const GIBS_CHECKED = {json.dumps(stamp)};\n"
        f"export const GIBS_LAYERS = {json.dumps(out, indent=1, ensure_ascii=False)};\n"
    )
    target = Path(__file__).resolve().parent.parent / "js" / "gibs-layers.js"
    target.write_text(js, encoding="utf-8")
    for o in out:
        print(o["id"], o["format"], o["tileMatrixSet"], o["period"], o["defaultTime"], len(o["intervals"]), "intervals")


if __name__ == "__main__":
    main()
